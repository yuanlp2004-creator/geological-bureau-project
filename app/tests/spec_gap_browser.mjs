import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { call, navigate } from './contract_browser_support.mjs'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const output = process.env.QA_DESKTOP_OUTPUT
await mkdir(output, { recursive: true })
const browser = process.env.QA_CDP ? await chromium.connectOverCDP(process.env.QA_CDP)
  : await chromium.launch({ headless: true, channel: 'msedge' })
const page = process.env.QA_CDP ? browser.contexts()[0].pages()[0] : await browser.newPage({ viewport: { width: 1440, height: 920 } })
const result = { status: 'failed', checks: [], desktop: Boolean(process.env.QA_CDP) }
const errors = []
const inputReady = (label, value) => page.waitForFunction(({ label, value }) =>
  [...document.querySelectorAll('label.field')].some((node) => node.querySelector('span')?.textContent === label && node.querySelector('input')?.value === value), { label, value })
page.on('pageerror', (error) => errors.push(error.message))
try {
  if (!process.env.QA_CDP) await page.goto(process.env.QA_BROWSER_URL)
  await page.getByLabel('用户名', { exact: true }).fill('spec-gap-operator')
  await page.getByLabel('密码', { exact: true }).fill('correct-horse')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByTestId('workspace').waitFor()
  const methods = await call(page, '/api/v1/methods')
  const method = methods.find((item) => item.name === 'Spec gap closure')
  const before = method.published_version.content_sha256

  await navigate(page, 'methods', '方法管理与参数', '.methods-page')
  const actual = page.getByLabel('实际基线波长 (nm)', { exact: true })
  await actual.fill(String(method.published_version.conditions.reference_wavelength_nm + .0108))
  await actual.press('Tab')
  await page.locator('output').filter({ hasText: /nm \(2 点\)/ }).waitFor()
  await page.getByRole('button', { name: '偏移清零', exact: true }).click()
  await page.locator('output').filter({ hasText: '0.0000 nm (0 点)' }).waitFor()
  const nextReference = method.published_version.conditions.reference_wavelength_nm + .005
  await page.getByLabel('基线波长 (nm)', { exact: true }).fill(String(nextReference))
  await page.getByLabel('基线波长 (nm)', { exact: true }).press('Tab')
  assert.equal(Number(await actual.inputValue()), nextReference)
  const methodPeriod = page.getByLabel('采样周期 (s)', { exact: true })
  assert.equal(await methodPeriod.inputValue(), '1.5')
  await methodPeriod.focus()
  await methodPeriod.press('Tab')
  assert.equal(await methodPeriod.evaluate((input) => input.validationMessage), '')
  await page.locator('.method-editor').screenshot({ path: path.join(output, 'reference-offset.png') })
  result.checks.push('reference delta in nm/pixels; clear and theoretical change update only the draft')
  await navigate(page, 'methods', '分析谱线', '.methods-page')
  await page.locator('.spectral-line-card').filter({ hasText: 'Cu' }).click()
  assert.equal(await page.getByLabel('曝光起始帧（0 继承方法）').inputValue(), '1')
  assert.equal(await page.getByLabel('曝光结束帧（0 继承方法）').inputValue(), '2')
  result.checks.push('single-line exposure interval is available in the existing spectral-line editor')

  await navigate(page, 'analysis-tests', '样品摄谱', '.sample-acquisition-page')
  await page.getByRole('button', { name: /known frames/ }).waitFor()
  const disclosure = page.getByRole('button', { name: '建立样品摄谱任务', exact: true })
  if (await disclosure.getAttribute('aria-expanded') !== 'true') await disclosure.click()
  const form = page.locator('.acquisition-form')
  await inputReady('采样周期 (秒)', '1.5')
  assert.equal(await form.getByLabel('采样次数', { exact: true }).inputValue(), '3')
  assert.equal(await form.getByLabel('采样周期 (秒)', { exact: true }).inputValue(), '1.5')
  await form.getByLabel('样品类型').selectOption('standard')
  await inputReady('重复次数', '3')
  assert.equal(await form.getByLabel('重复次数', { exact: true }).inputValue(), '3')
  await form.getByLabel('样品类型').selectOption('test')
  await form.getByLabel('临时样号', { exact: true }).fill('D9')
  await inputReady('重复次数', '4')
  assert.equal(await form.getByLabel('重复次数', { exact: true }).inputValue(), '4')
  await form.getByLabel('重复次数', { exact: true }).fill('7')
  const createResponse = page.waitForResponse((response) => response.url().endsWith('/api/v1/acquisitions/tasks') && response.request().method() === 'POST')
  await form.getByRole('button', { name: '创建任务', exact: true }).click()
  const taskResponse = await createResponse
  assert.equal(taskResponse.status(), 201)
  const task = await taskResponse.json()
  assert.equal(task.repeat_count, 7)
  assert.equal(task.pre_excitation_seconds, 2)
  assert.equal(task.storage_mode, 'full_interval')
  result.checks.push('method excitation/type defaults, explicit repeat override, and full-frame retention')

  await navigate(page, 'analysis-tests', '样品分析', '.analysis-page')
  await page.getByRole('button', { name: '谱图与测量', exact: true }).click()
  await page.getByText('校线', { exact: true }).click()
  const previewResponse = page.waitForResponse((response) => response.url().endsWith('/calibration') && response.request().method() === 'GET')
  await page.getByRole('button', { name: '日常校线预览', exact: true }).click()
  assert.equal((await previewResponse).status(), 200)
  await page.getByText('有效峰', { exact: true }).first().waitFor()
  await page.locator('.analysis-spectrum').screenshot({ path: path.join(output, 'daily-calibration.png') })
  const saveResponse = page.waitForResponse((response) => response.url().endsWith('/calibration') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '保存位置为方法草稿', exact: true }).click()
  assert.equal((await saveResponse).status(), 200)
  const after = await call(page, `/api/v1/methods/${method.id}`)
  assert.equal(after.published_version.content_sha256, before)
  assert.equal(after.version.state, 'draft')
  result.checks.push('daily calibration preview/save creates a new draft and retains the published method')
  assert.equal(await page.getByRole('button', { name: '导出谱线全时观察表', exact: true }).count(), 0)
  result.checks.push('time-series export action removed while daily calibration remains available')

  await navigate(page, 'data', '重新计算', '.postprocessing-page')
  await page.locator('.postprocessing-legacy-tools > summary').click()
  await page.locator('.postprocessing-source-surface summary').click()
  const storage = page.getByLabel('转换存储模式')
  assert.equal(await storage.inputValue(), 'full_interval')
  await storage.selectOption('averaged')
  assert.equal(await storage.inputValue(), 'averaged')
  await navigate(page, 'data', '重新计算', '.postprocessing-page')
  await page.getByLabel('已核对方法修改，允许重算较旧 PDT（记录此确认）').waitFor()
  result.checks.push('EDT storage choice and explicit older-PDT confirmation are present')

  await navigate(page, 'data', '打印与导出', '[data-testid=data-processing-page]')
  await page.getByRole('tab', { name: '分析报告', exact: true }).click()
  await page.getByLabel('报告来源').selectOption('dat')
  await page.getByLabel('旧结果单位', { exact: true }).fill('ug/g')
  await page.locator('.report-run-row').filter({ hasText: 'DAT #1' }).locator('input').check()
  const reportResponse = page.waitForResponse((response) => response.url().endsWith('/api/v1/reports') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '建立报告版本', exact: true }).click()
  const created = await reportResponse
  assert.equal(created.status(), 201)
  const report = await created.json()
  assert.equal(report.model.source_kind, 'legacy_dat')
  assert.equal(report.model.rows.length, 270)
  await page.getByRole('button', { name: '预览', exact: true }).click()
  const frame = page.frameLocator('.report-preview-modal iframe')
  await frame.getByRole('heading', { name: '旧 DAT 来源', exact: true }).waitFor()
  await page.locator('.report-preview-modal').screenshot({ path: path.join(output, 'legacy-dat-report.png') })
  await page.locator('.report-preview-modal').getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '确认报告', exact: true }).click()
  await page.locator('.state-chip').filter({ hasText: 'confirmed' }).waitFor()
  await page.getByLabel('输出目录', { exact: true }).fill(output)
  await page.getByLabel('文件名', { exact: true }).fill('legacy-dat-report')
  const pdfResponse = page.waitForResponse((response) => response.url().endsWith(`/reports/${report.id}/exports`))
  await page.getByRole('button', { name: 'PDF', exact: true }).click()
  const pdfExport = await (await pdfResponse).json()
  assert.ok((await readFile(pdfExport.path)).subarray(0, 5).equals(Buffer.from('%PDF-')))
  result.checks.push('real DAT report selection, explicit unit/provenance, preview, confirmation, and PDF export')
  assert.deepEqual(errors, [])
  result.status = 'passed'
} catch (error) {
  result.error = error.stack
  result.outputs = await page.locator('output').allTextContents()
  await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {})
  throw error
} finally {
  await writeFile(process.env.QA_DESKTOP_RESULT, JSON.stringify(result, null, 2))
  await browser.close()
}
