import assert from 'node:assert/strict'
import { call, navigate } from './contract_browser_support.mjs'

export async function checkBluetoothDelete(page, result) {
  const original=await call(page,'/api/v1/devices/bluetooth'),profiles=await call(page,'/api/v1/devices/profiles')
  const target=original.devices.find(item=>item.ports.length===0)??original.devices[0]
  const selected=original.devices.find(item=>item.address!==target?.address&&item.ports.length)??original.devices.find(item=>item.address!==target?.address)
  assert.ok(target&&selected,'Test host must expose at least two Bluetooth entries')
  await navigate(page,'tools','设备连接','[data-testid="device-connection"]')
  const panel=page.getByTestId('device-connection'),picker=panel.getByRole('combobox',{name:'Windows蓝牙设备',exact:true})
  const popup=panel.getByRole('dialog',{name:'蓝牙设备列表',exact:true})
  const open=async()=>{if(await picker.getAttribute('aria-expanded')!=='true')await picker.click();await popup.waitFor()}
  const choose=async address=>{await open();await popup.locator(`[data-bluetooth-address="${address}"] .bluetooth-device-option`).click()}
  await choose(selected.address)
  assert.equal(await popup.count(),0)
  assert.equal(await panel.locator('.bluetooth-device-delete').count(),0)
  await open()
  const rows=popup.locator('[data-bluetooth-address]')
  assert.equal(await rows.count(),original.devices.length)
  for(const row of await rows.all()) {
    const remove=row.locator('.bluetooth-device-delete'),rowBox=await row.boundingBox(),buttonBox=await remove.boundingBox()
    assert.equal((await remove.innerText()).trim(),'')
    assert.ok(Math.abs(rowBox.x+rowBox.width-buttonBox.x-buttonBox.width)<6)
  }
  result.checks.push('每个设备行最右侧仅有垃圾桶图标，列表外没有删除按钮')
  const remove=popup.locator(`[data-bluetooth-address="${target.address}"] .bluetooth-device-delete`)
  const pattern=`**/api/v1/devices/bluetooth/${target.address}`
  await page.route(pattern,route=>route.fulfill({status:503,json:{detail:{message:'测试：删除保存失败'}}}))
  await remove.click()
  await panel.getByRole('alert').filter({hasText:'删除保存失败'}).waitFor()
  await page.waitForFunction(()=>!document.querySelector('[data-testid="device-connection"] fieldset')?.disabled)
  assert.equal(await popup.locator(`[data-bluetooth-address="${target.address}"]`).count(),1)
  assert.equal(await picker.getAttribute('value'),selected.address)
  await page.unroute(pattern)
  result.checks.push('行内删除保存失败时保留原设备和当前选择')
  const response=page.waitForResponse(r=>r.request().method()==='DELETE'&&r.url().endsWith(`/devices/bluetooth/${target.address}`))
  await remove.click();assert.equal((await response).status(),200)
  await page.waitForFunction(address=>!document.querySelector(`[data-bluetooth-address="${address}"]`),target.address)
  assert.equal(await popup.isVisible(),true)
  assert.equal(await picker.getAttribute('value'),selected.address)
  result.checks.push('行内删除只作用于该设备，不误选或清空另一设备，列表保持打开')
  await page.route('**/api/v1/devices/bluetooth',route=>route.fulfill({json:original}))
  await panel.getByRole('button',{name:'刷新设备与端口',exact:true}).click()
  await page.waitForFunction(()=>!document.querySelector('[data-testid="device-connection"] fieldset')?.disabled)
  await open();assert.equal(await popup.locator(`[data-bluetooth-address="${target.address}"]`).count(),0)
  await page.unroute('**/api/v1/devices/bluetooth')
  result.checks.push('刷新和过期响应均不会恢复已删除的行')
  await page.reload();await page.locator('[data-navigation-group="tools"]').waitFor()
  await navigate(page,'tools','设备连接','[data-testid="device-connection"]')
  await page.waitForFunction(()=>document.querySelector('[data-testid="device-connection"] .connection-state')?.textContent==='未连接')
  await open();assert.equal(await popup.locator(`[data-bluetooth-address="${target.address}"]`).count(),0)
  assert.equal((await call(page,'/api/v1/devices/bluetooth')).devices.some(item=>item.address===target.address),false)
  assert.deepEqual(await call(page,'/api/v1/devices/profiles'),profiles)
  result.checks.push('重新打开页面后永久删除仍生效，原设备档案保持')
  await picker.press('Escape');assert.equal(await popup.count(),0)
  await picker.press('ArrowDown');await popup.waitFor()
  await page.waitForFunction(()=>document.activeElement?.classList.contains('bluetooth-device-option'))
  await page.keyboard.press('ArrowDown')
  await page.waitForFunction(()=>Boolean(document.activeElement?.closest('[data-bluetooth-address]')))
  const keyboardAddress=await page.evaluate(()=>document.activeElement.closest('[data-bluetooth-address]')?.getAttribute('data-bluetooth-address'))
  assert.ok(keyboardAddress)
  await page.keyboard.press('ArrowRight')
  assert.equal(await page.evaluate(()=>document.activeElement?.classList.contains('bluetooth-device-delete')),true)
  await page.keyboard.press('ArrowLeft')
  assert.equal(await page.evaluate(()=>document.activeElement?.classList.contains('bluetooth-device-option')),true)
  await page.keyboard.press('Enter')
  assert.equal(await popup.count(),0);assert.equal(await picker.getAttribute('value'),keyboardAddress)
  await open();await page.keyboard.press('Escape');assert.equal(await popup.count(),0)
  result.checks.push('键盘上下选择、Enter确认、Escape关闭均正常')
  await choose(selected.address);await open()
  assert.equal((await call(page,'/api/v1/devices/diagnostics')).adapter.connected,false)
}
