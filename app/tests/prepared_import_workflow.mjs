import assert from 'node:assert/strict'
import { openViewerFiles } from './legacy_desk_test_support.mjs'

export async function checkPreparedImport(page, result, output) {
  const meanName = '独立导入均值样品-' + Date.now()
  const fullName = meanName.replace('均值', '全时')
  const navigate = async (group, name) => {
    await page.locator(`[data-navigation-group="${group}"]`).click()
    await page.getByRole('menuitem').filter({has:page.getByText(name,{exact:true})}).click()
    await page.keyboard.press('Escape')
    await page.mouse.move(900,500)
  }
  await navigate('tools', '导入预备摄谱文件')
  const workspace = page.getByTestId('prepared-import-page')
  await workspace.waitFor()
  const source = workspace.getByLabel('导入蒸发文件', { exact: true })
  await source.selectOption({ index: 1 })
  await workspace.getByLabel('导入区间', { exact: true }).waitFor()
  await page.waitForFunction(()=>document.querySelector('[aria-label="导入区间"]')?.value === '1-3')
  await workspace.getByRole('button', { name: '全部选择', exact: true }).click()
  assert.equal(await workspace.locator('[aria-label="源记录"] tbody input:checked').count(), 2)
  await workspace.getByRole('button', { name: '反向选择', exact: true }).click()
  assert.equal(await workspace.locator('[aria-label="源记录"] tbody input:checked').count(), 0)
  await workspace.getByRole('button', { name: '全部选择', exact: true }).click()
  await workspace.getByLabel('输出样品集', { exact: true }).fill(meanName)
  await workspace.getByLabel('导入区间', { exact: true }).fill('1-4')
  await workspace.getByRole('button', { name: '导入记录', exact: true }).click()
  await workspace.getByRole('alert').filter({hasText:'有效的帧区间'}).waitFor()
  result.checks.push('独立工具入口、当前文件全选反选及越界区间拒绝')
  await workspace.getByLabel('导入区间', { exact: true }).fill('2-3')
  let attempts=[]
  await page.route('**/api/v1/postprocessing/prepared-import',async route=>{
    if(route.request().method()!=='POST')return route.continue()
    attempts.push(route.request().postDataJSON())
    if(attempts.length===1)return route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:{message:'测试连接中断，请重试'}})})
    return route.continue()
  })
  await workspace.getByRole('button', { name: '导入记录', exact: true }).click()
  await workspace.getByRole('alert').filter({hasText:'测试连接中断'}).waitFor()
  assert.equal(await workspace.getByLabel('输出样品集',{exact:true}).inputValue(),meanName)
  await workspace.getByRole('button', { name: '导入记录', exact: true }).click()
  await workspace.getByRole('status').filter({hasText:'输出样品集共 2 条'}).waitFor()
  assert.equal(attempts.length,2);assert.equal(attempts[0].request_id,attempts[1].request_id)
  await page.unroute('**/api/v1/postprocessing/prepared-import')
  assert.equal(await workspace.locator('[aria-label="输出记录"] tbody tr').count(),2)
  result.checks.push('真实均值转换、失败保留草稿、同请求幂等重试及右侧结果')
  await workspace.getByRole('button',{name:'查看谱图',exact:true}).click()
  await page.getByTestId('legacy-spectrum-surface').waitFor()
  const sourceDialog = await openViewerFiles(page.getByTestId('spectrum-viewer-page'))
  const selectedFile = await sourceDialog.getByLabel('当前谱文件',{exact:true}).locator('option:checked').innerText()
  assert.ok(selectedFile.includes(meanName))
  assert.match(selectedFile,/2 条/)
  await sourceDialog.getByRole('button',{name:'关闭选择谱文件',exact:true}).click()
  result.checks.push('输出样品集直接打开查看谱图并含两条样品')
  await navigate('tools','导入预备摄谱文件')
  await source.selectOption({index:1})
  await workspace.getByRole('button',{name:'全部选择',exact:true}).click()
  await workspace.getByLabel('选择已有输出',{exact:true}).selectOption({label:meanName})
  await workspace.getByLabel('导入区间',{exact:true}).fill('2-3')
  await workspace.getByRole('button',{name:'导入记录',exact:true}).click()
  let dialog=page.getByRole('dialog',{name:'输出样品集已存在',exact:true})
  await dialog.getByRole('button',{name:'取消',exact:true}).click()
  assert.equal(await workspace.locator('[aria-label="输出记录"] tbody tr').count(),2)
  await workspace.getByRole('button',{name:'导入记录',exact:true}).click()
  await dialog.getByRole('button',{name:'追加记录',exact:true}).click()
  await workspace.getByRole('status').filter({hasText:'输出样品集共 4 条'}).waitFor()
  await workspace.getByRole('button',{name:'导入记录',exact:true}).click()
  await dialog.getByRole('button',{name:'替换样品集',exact:true}).click()
  await workspace.getByRole('status').filter({hasText:'输出样品集共 2 条'}).waitFor()
  result.checks.push('同名目标取消、追加与替换，结果列表即时同步')
  await workspace.getByLabel('导出格式',{exact:true}).selectOption('full_interval')
  assert.equal(await workspace.getByLabel('输出样品集',{exact:true}).inputValue(),'')
  await workspace.getByLabel('输出样品集',{exact:true}).fill(fullName)
  await workspace.getByRole('button',{name:'导入记录',exact:true}).click()
  await workspace.getByRole('status').filter({hasText:'输出样品集共 2 条'}).waitFor()
  await workspace.getByRole('button',{name:'保存色散',exact:true}).click()
  await workspace.getByRole('status').filter({hasText:'新版工作副本'}).waitFor()
  result.checks.push('全时格式切换清目标、区间逐帧转换及色散工作副本保存')
  for(const [width,height] of [[1440,1000],[1060,740]]) {
    if(!process.env.QA_CDP)await page.setViewportSize({width,height})
    else await page.evaluate(async({width,height})=>{await window.__TAURI__.core.invoke('plugin:window|set_size',{value:{Logical:{width,height}}})},{width,height})
    await page.waitForTimeout(150)
    const geometry=await workspace.evaluate(element=>({viewport:innerWidth,scroll:document.documentElement.scrollWidth,
      panels:[...element.querySelectorAll('.prepared-record-panel')].map(panel=>({width:panel.clientWidth,height:panel.clientHeight}))}))
    assert.ok(geometry.scroll<=geometry.viewport+1,JSON.stringify(geometry))
    assert.ok(geometry.panels.every(panel=>panel.width>=210&&panel.height>=300),JSON.stringify(geometry))
    await page.screenshot({path:`${output}/prepared-import-${width}.png`,fullPage:true})
    result.layouts.push({width,height,...geometry})
  }
  await navigate('data','重新计算')
  await page.getByTestId('postprocessing-page').waitFor()
  assert.equal(await page.getByText('旧记录区间查看与 EDT 转换',{exact:true}).count(),0)
  assert.equal(await page.getByRole('button',{name:'打开蒸发摄谱文件',exact:true}).count(),0)
  result.checks.push('重新计算独立保留，已移除EDT折叠区及打开蒸发文件入口')
  await navigate('tools','导入预备摄谱文件')
  await source.selectOption({index:1})
  await workspace.getByLabel('选择已有输出',{exact:true}).selectOption({label:meanName})
  await workspace.getByRole('button',{name:'全部选择',exact:true}).click()
  await workspace.getByLabel('导入区间',{exact:true}).fill('2-3')
}
