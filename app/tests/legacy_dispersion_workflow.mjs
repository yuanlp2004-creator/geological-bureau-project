import assert from 'node:assert/strict'
import path from 'node:path'
import {call,navigate} from './contract_browser_support.mjs'

export async function checkLegacyDispersion(page,fixture,result,output) {
  const check=text=>{result.checks.push(text);console.log(`PASS: ${text}`)}
  const entries=(await call(page,'/api/v1/capabilities')).capabilities.flatMap(item=>item.navigation_entries)
  const go=async view=>{const entry=entries.find(e=>e.page==='dispersion'&&(view==='curve'?e.view==='curve':e.view!=='curve'));await navigate(page,entry.group,entry.label,'[data-testid="dispersion-page"]')}
  const host=page.getByTestId('dispersion-page'), button=name=>host.getByRole('button',{name,exact:true})
  let task=await call(page,'/api/v1/dispersion/tasks',{name:'旧版色散对齐验收',ccd_indices:[0,1],frame_count:3,dark_frame_count:1,pre_excitation_seconds:0})
  task=await call(page,`/api/v1/dispersion/tasks/${task.id}/start`,{})
  for(let i=0;i<30&&task.status!=='completed';i++)task=await call(page,`/api/v1/dispersion/tasks/${task.id}/step`,{})
  assert.equal(task.status,'completed')
  await call(page,`/api/v1/dispersion/tasks/${task.id}/gaps/0?gap_um=9800&legacy_limits=true`,{},'PATCH')
  await go('curve')
  const coordinate=host.getByLabel('定位谱线',{exact:true})
  for(const [ccd,point] of [[1,101],[1,601],[2,153],[2,353]]) {
    await coordinate.fill(`${ccd},${point}`);await coordinate.press('Enter')
    await page.waitForFunction(()=>!document.querySelector('button[aria-label="增加谱线"]').disabled)
    const response=page.waitForResponse(r=>r.url().endsWith('/line-points')&&r.request().method()==='POST')
    await button('增加谱线').click();assert.equal((await response).status(),201)
  }
  check('主谱图选点＋增加谱线，保留CCD点位，波长在旧式网格中填写')
  const open=async()=>{await button('拟合曲线').click();await page.getByRole('dialog',{name:'色散曲线',exact:true}).waitFor();return page.getByRole('dialog',{name:'色散曲线',exact:true})}
  let dialog=await open()
  assert.deepEqual(await dialog.locator('thead th').allTextContents(),['序号','谱线波长','谱线位置','测量步数','校正步数','步数误差'])
  assert.equal(await dialog.getByLabel('CCD区间').inputValue(),'-1')
  assert.ok(await dialog.getByLabel('CCD间隔（μm）').isDisabled())
  assert.equal(await dialog.getByRole('button',{name:'添加',exact:true}).count(),0)
  assert.equal(await dialog.locator('.line-actions').count(),0)
  assert.ok(await dialog.getByRole('button',{name:'拟合曲线',exact:true}).isDisabled())
  for(const [index,wave] of [250,255,278,280].entries())await dialog.getByLabel(`谱线${index+1}波长（nm）`,{exact:true}).fill(String(wave))
  const fitting=page.waitForResponse(r=>r.url().endsWith('/calibrations/fit')&&r.request().method()==='POST')
  await dialog.getByRole('button',{name:'拟合曲线',exact:true}).click();assert.equal((await fitting).status(),201)
  await page.waitForFunction(()=>document.querySelector('.dispersion-legacy-results dd')?.textContent==='-24900.0')
  assert.equal(await dialog.locator('.dispersion-legacy-results dd').nth(3).innerText(),'0.01000')
  assert.equal(await dialog.locator('tbody tr').nth(2).locator('td').nth(2).innerText(),'(2,153)')
  assert.equal(await dialog.locator('tbody tr').nth(2).locator('td').nth(3).innerText(),'2900.0')
  assert.ok(await dialog.getByRole('button',{name:'保存曲线',exact:true}).isEnabled())
  await dialog.getByLabel('谱线1波长（nm）',{exact:true}).fill('159')
  await dialog.getByLabel('谱线1波长（nm）',{exact:true}).press('Tab')
  assert.equal(await dialog.getByLabel('谱线1波长（nm）',{exact:true}).inputValue(),'250.0000')
  assert.equal((await call(page,`/api/v1/dispersion/tasks/${task.id}`)).lines[0].wavelength_nm,250)
  check('六列表格与六项计算结果按旧版口径显示，跨CCD测量步数含间隔，二次拟合与每步波长正确')
  await dialog.getByLabel('CCD区间').selectOption('0');assert.equal(await dialog.getByLabel('CCD间隔（μm）').inputValue(),'9800')
  await dialog.getByLabel('标尺（μm）').selectOption('5')
  const gap=page.waitForResponse(r=>r.url().includes('/gaps/0')&&r.request().method()==='PATCH')
  await dialog.getByRole('button',{name:'增大CCD间隔',exact:true}).click();assert.equal((await gap).status(),200)
  await dialog.getByText('谱线或CCD间隔已改变，请重新拟合。',{exact:true}).waitFor()
  assert.equal(await dialog.locator('tbody tr').nth(2).locator('td').nth(3).innerText(),'2900.4')
  assert.equal(await dialog.locator('tbody tr').nth(2).locator('td').nth(4).innerText(),'')
  assert.ok(await dialog.getByRole('button',{name:'保存曲线',exact:true}).isDisabled())
  const before=(await call(page,`/api/v1/dispersion/tasks/${task.id}`)).calibrations.length
  assert.equal(before,1,'调间隔不能自动拟合')
  await dialog.getByRole('button',{name:'拟合曲线',exact:true}).click()
  await page.waitForFunction(()=>!document.querySelector('.dispersion-legacy-toolbar button:nth-last-child(2)').disabled)
  await dialog.getByRole('button',{name:'保存曲线',exact:true}).click()
  let saving=page.getByRole('dialog',{name:'保存色散曲线',exact:true})
  await saving.screenshot({path:path.join(output,'save-curve-dialog.png')})
  await saving.getByLabel('色散曲线名称').fill('取消后保留的草稿')
  await saving.getByRole('button',{name:'取消',exact:true}).click()
  assert.ok(await dialog.isVisible());assert.ok(await dialog.getByRole('button',{name:'保存曲线',exact:true}).isEnabled())
  check('区间初始未选择、标尺调节、只重算步数不自动拟合；结果失效与保存取消保护正确')
  for(const [theme,width,height] of [['light',1440,1000],['dark',1060,680],['light',2560,1200]]) {
    if(process.env.QA_CDP)await page.evaluate(value=>window.__TAURI__.core.invoke('plugin:window|set_size',{value:{Logical:value}}),{width,height})
    else await page.setViewportSize({width,height})
    await page.evaluate(theme=>document.documentElement.dataset.theme=theme,theme)
    const layout=await dialog.evaluate(node=>{
      const r=node.getBoundingClientRect(),body=node.querySelector('.dispersion-legacy-body'),table=node.querySelector('.dispersion-legacy-table'),results=node.querySelector('.dispersion-legacy-results')
      return {inside:r.left>=0&&r.top>=0&&r.right<=innerWidth+1&&r.bottom<=innerHeight+1,noOverflow:node.scrollWidth<=node.clientWidth+1,
        columns:getComputedStyle(body).gridTemplateColumns.split(' ').length,sideBySide:results.getBoundingClientRect().left>table.getBoundingClientRect().left+table.clientWidth-2}
    })
    assert.ok(layout.inside&&layout.noOverflow&&layout.sideBySide,JSON.stringify(layout));assert.equal(layout.columns,2)
    await page.screenshot({path:path.join(output,`legacy-fit-${theme}-${width}.png`)});result.layouts.push({theme,width,height})
  }
  check('独立窗体顶部工具、左表右结果，普通／最小／超宽窗口及明暗主题无横向溢出')
  await dialog.getByRole('button',{name:'保存曲线',exact:true}).click();saving=page.getByRole('dialog',{name:'保存色散曲线',exact:true})
  await saving.getByLabel('色散曲线名称').fill('旧式保存验收')
  const saved=page.waitForResponse(r=>r.url().includes('/save?name=')&&r.request().method()==='POST')
  await saving.getByRole('button',{name:'保存',exact:true}).click();assert.equal((await saved).status(),200)
  await dialog.waitFor({state:'hidden'})
  let current=await call(page,`/api/v1/dispersion/tasks/${task.id}`)
  const version=current.calibrations[0];assert.equal(version.name,'旧式保存验收');assert.equal(version.state,'published')
  assert.ok((await call(page,'/api/v1/dispersion/options')).calibration_versions.some(c=>c.id===version.id))
  check('保存曲线弹出命名窗口，真实保存可选用版本并退出拟合窗口，取消草稿保留')
  const line=current.lines[0]
  const menu=async()=>{await host.locator(`[data-line-id="${line.id}"] button`).click({button:'right'});await page.getByRole('menu',{name:'谱线位置菜单'}).waitFor()}
  await menu();await page.getByRole('menuitem',{name:'保存全部位置',exact:true}).click()
  await page.waitForFunction(()=>!document.querySelector('button[aria-label="拟合曲线"]').disabled)
  await button('拟合曲线').focus()
  const moved=page.waitForResponse(r=>r.url().includes(`/lines/${line.id}/move`)&&r.request().method()==='POST')
  await page.keyboard.press('Control+ArrowRight');assert.equal((await moved).status(),200)
  await menu();await page.getByRole('menuitem',{name:'还原全部位置',exact:true}).click()
  await page.waitForFunction(()=>!document.querySelector('button[aria-label="拟合曲线"]').disabled)
  current=await call(page,`/api/v1/dispersion/tasks/${task.id}`)
  assert.equal(current.lines.find(l=>l.id===line.id).located_position,line.located_position)
  check('谱线标记／列表右键菜单、Ctrl方向键微移、保存／还原全部位置接通；已保存曲线保持')
  const originalMethod=await call(page,`/api/v1/methods/${fixture.method_id}`)
  const method=await call(page,'/api/v1/methods',{name:'选用新色散曲线验收'})
  const methodEntry=entries.find(entry=>entry.page==='methods'&&entry.view==='conditions')
  await navigate(page,methodEntry.group,methodEntry.label,'[data-testid="methods-page"]')
  const methodPage=page.getByTestId('methods-page')
  await methodPage.getByLabel('选择编辑方法').selectOption(String(method.id))
  const calibration=methodPage.getByLabel('色散曲线',{exact:true})
  await calibration.locator(`option[value="${version.calibration_id}"]`).waitFor({state:'attached'})
  await calibration.selectOption(String(version.calibration_id))
  const savingMethod=page.waitForResponse(r=>r.url().endsWith(`/methods/${method.id}/save`)&&r.request().method()==='POST')
  await methodPage.getByRole('button',{name:'保存',exact:true}).click()
  const methodResponse=await savingMethod;assert.equal(methodResponse.status(),200,await methodResponse.text())
  const savedMethod=await methodResponse.json()
  assert.equal(savedMethod.version.conditions.dispersion_calibration_id,version.calibration_id)
  assert.equal(savedMethod.version.conditions.ccd_layout_id,version.ccd_layout_id)
  assert.deepEqual(await call(page,`/api/v1/methods/${fixture.method_id}`),originalMethod)
  check('保存后的曲线可在真实方法参数中选用并保存确切布局与系数，原方法保持')
  await go('capture')
  const taskButton=host.locator(`[data-task-id="${task.id}"] button`)
  if(await host.getAttribute('data-stage')==='tasks') {await taskButton.waitFor();await taskButton.click()}
  dialog=await open()
  assert.equal(await host.locator('.capture-processing').count(),0)
  assert.equal(await dialog.locator('thead th').count(),6)
  assert.equal(await dialog.locator('.dispersion-legacy-results dd').first().innerText(),'—','重新打开需要明确拟合')
  await dialog.getByRole('button',{name:'拟合曲线',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.dispersion-legacy-results dd')?.textContent?.trim()!=='—')
  if(process.env.QA_CDP)await page.evaluate(value=>window.__TAURI__.core.invoke('plugin:window|set_size',{value:{Logical:value}}),{width:1440,height:1000})
  else await page.setViewportSize({width:1440,height:1000})
  await page.screenshot({path:path.join(output,'review-legacy-fit.png')})
  check('色散摄谱与色散曲线共用同一旧式独立窗口；重新打开不展示陈旧拟合结果')
  result.reviewTaskId=task.id;result.savedCalibrationId=version.id
}
