import assert from 'node:assert/strict'
import path from 'node:path'
import { call, navigate } from './contract_browser_support.mjs'

export async function checkRuntimeMessages(page, result, output) {
  const check = message => { result.checks.push(message); console.log(`PASS: ${message}`) }
  const panel = page.getByTestId('runtime-messages')
  const rows = () => panel.locator('.runtime-message-row')
  const tab = name => panel.getByRole('tab', { name: new RegExp(`^${name}`) })
  const filter = panel.getByLabel('过滤信息记录')
  const level = panel.getByLabel('信息记录日志级别')
  const workspaceReady = async () => {
    await page.getByTestId('workspace').getByText(/SQLite schema v\d+/, {exact:true}).waitFor()
    await page.getByTestId('workspace').locator('.quick-surface').waitFor()
  }
  const log = (message, severity='info', channel='general') => call(page, '/api/v1/logs', {
    category: channel === 'communication' ? 'acquisition' : 'analysis', severity, message, details: { channel }
  })
  await panel.waitFor()
  await workspaceReady()
  assert.equal(await panel.count(), 1)
  const workspace = page.getByTestId('workspace')
  const originalMessages = workspace.getByTestId('workspace-messages')
  await originalMessages.waitFor()
  assert.equal(await workspace.locator('.primary-column > .status-surface').count(), 1)
  assert.equal(await workspace.locator('.primary-column > .message-surface').count(), 1)
  for (const card of ['quick-surface', 'workspace-diagnostics', 'protocol-surface']) {
    assert.equal(await workspace.locator(`.secondary-column > .${card}`).count(), 1)
  }
  assert.equal(await originalMessages.getByRole('combobox', {name:'按状态过滤'}).count(), 1)
  assert.equal(await originalMessages.getByRole('button', {name:'保存消息'}).count(), 1)
  assert.equal(await originalMessages.getByRole('button', {name:'复制选中消息'}).count(), 1)
  assert.equal(await panel.locator('.runtime-message-list').isVisible(), false)
  check('Original workbench method/messages and right-hand information cards restored; footer starts folded')
  await panel.getByRole('button',{name:'展开信息记录'}).click()
  assert.deepEqual((await panel.getByRole('tab').allTextContents()).map(text => text.replace(/\s*\d+\s*$/, '').trim()), ['常规信息','通信命令'])
  assert.equal(await panel.getByRole('button', { name: /保存|复制|全选|记录请求/ }).count(), 0)
  await log('QA-常规-信息')
  await log('QA-常规-详细', 'debug')
  await log('QA-常规-完成', 'success')
  await log('QA-常规-提示', 'warning')
  await log('QA-通信-信息', 'info', 'communication')
  await log('QA-通信-详细', 'debug', 'communication')
  await filter.fill('QA-常规')
  await rows().filter({ hasText:'QA-常规-提示' }).waitFor()
  assert.equal(await rows().count(), 3)
  await level.selectOption('detailed'); assert.equal(await rows().count(), 4)
  assert.equal(await rows().locator('.runtime-message-context').count(), 4)
  assert.match(await tab('常规信息').innerText(), /4\s*$/)
  await level.selectOption('brief'); assert.equal(await rows().count(), 2)
  assert.equal(await rows().locator('.runtime-message-context').count(), 0)
  assert.match(await tab('常规信息').innerText(), /2\s*$/)
  await filter.fill('不存在的记录'); await panel.getByText('没有匹配的记录').waitFor()
  await level.selectOption('default'); await filter.fill('QA-通信'); await tab('通信命令').click()
  await rows().filter({ hasText:'QA-通信-信息' }).waitFor()
  assert.equal(await rows().count(), 1)
  await level.selectOption('detailed'); assert.equal(await rows().count(), 2)
  check('Two legacy categories with detailed/default/brief display and text filtering; no request logging or extra actions')

  await panel.getByRole('button', {name:'暂停',exact:true}).click()
  await log('QA-通信-暂停期间', 'info', 'communication')
  await page.waitForResponse(response => response.request().method()==='GET' && response.url().includes('/api/v1/logs?limit=500'))
  assert.equal(await rows().count(), 2)
  await panel.getByRole('button',{name:'继续',exact:true}).click()
  await rows().filter({hasText:'QA-通信-暂停期间'}).waitFor()
  const before = await call(page, '/api/v1/logs?limit=500')
  await panel.getByRole('button',{name:'清屏',exact:true}).click()
  assert.equal(await rows().count(), 0)
  const after = await call(page, '/api/v1/logs?limit=500')
  assert.deepEqual(after.map(row=>row.id), before.map(row=>row.id))
  await log('QA-通信-清屏之后','info','communication')
  await rows().filter({hasText:'QA-通信-清屏之后'}).waitFor()
  assert.equal(await rows().count(), 1)
  await tab('常规信息').click(); await filter.fill('QA-常规'); assert.equal(await rows().count(), 4)
  check('Pause freezes display and resumes pending messages; clearing one category preserves stored records and the other category')

  const profiles=await call(page,'/api/v1/devices/profiles')
  await call(page,'/api/v1/devices/connect',{profile_id:profiles[0].id})
  await call(page,'/api/v1/devices/debug/start',{sample:'280-288.acq',seed:19})
  await call(page,'/api/v1/devices/debug/step',{})
  await call(page,'/api/v1/devices/debug/stop',{})
  await call(page,'/api/v1/devices/disconnect',{})
  await tab('通信命令').click(); await filter.fill('模拟设备已连接')
  await rows().filter({hasText:'模拟设备已连接'}).waitFor()
  await filter.fill('收到'); await level.selectOption('detailed')
  const stored=await call(page,'/api/v1/logs?limit=500')
  assert.ok(stored.some(row=>row.details?.channel==='communication' && row.severity==='debug'))
  const acquisitions=await call(page,'/api/v1/acquisitions/tasks')
  const candidate=acquisitions.find(row=>row.sample_name==='S16-A')
  assert.ok(candidate,'Expected the S16 immutable spectrum fixture')
  const existing=await call(page,`/api/v1/acquisitions/tasks/${candidate.id}`)
  const task=await call(page,'/api/v1/analyses/runs',{name:'底边信息验证',method_version_id:existing.method_version_id,acquisition_sample_ids:existing.samples.map(row=>row.id),slow_mode:false})
  await call(page,`/api/v1/analyses/runs/${task.id}/start`,{})
  const messages=await call(page,'/api/v1/logs?limit=500')
  assert.ok(messages.some(row=>row.details?.source==='analysis' && row.details?.channel==='general'))
  check('Actual simulator events reach communication records; actual analysis progress reaches general records')

  // Check the actual task output too: fabricated severity rows alone miss the
  // real case where every task message has the same info level.
  await tab('常规信息').click(); await filter.fill('分析运行已开始')
  await level.selectOption('default')
  await rows().filter({hasText:'分析运行已开始'}).waitFor()
  const actualDefaultCount=await rows().count()
  assert.ok(actualDefaultCount>0)
  assert.equal(await rows().locator('.runtime-message-context').count(),0)
  await level.selectOption('detailed')
  assert.equal(await rows().count(),actualDefaultCount)
  const context=rows().first().locator('.runtime-message-context')
  const actualContext=await context.innerText()
  assert.match(actualContext,new RegExp(`样品分析.*任务 ${task.id}.*analysis.run.started`))
  result.logLevels={actualAnalysisTaskId:task.id,defaultRows:actualDefaultCount,detailedRows:await rows().count(),detailedContext:actualContext}
  await page.screenshot({path:path.join(output,'information-level-detailed.png'),fullPage:true})
  await level.selectOption('brief'); assert.equal(await rows().count(),0)
  result.logLevels.briefRows=await rows().count()
  await level.selectOption('detailed'); await filter.fill(`任务 ${task.id}`)
  assert.ok(await rows().count()>0)
  await originalMessages.getByRole('combobox',{name:'按状态过滤'}).selectOption('error')
  assert.equal(await originalMessages.locator('.message-row:not(:has(.severity-label.error))').count(),0)
  await originalMessages.getByRole('combobox',{name:'按状态过滤'}).selectOption('all')
  await originalMessages.locator('.message-row input').first().check()
  await originalMessages.getByText('已选 1 条',{exact:true}).waitFor()
  await originalMessages.locator('.message-row input').first().uncheck()
  check('Real analysis messages change between default/brief/detailed; detailed shows actual task/source/code and category counts follow filtering')

  await filter.fill(''); await level.selectOption('default'); await tab('常规信息').click()
  await navigate(page,'system','软件设置','.settings-page')
  assert.equal(await panel.count(),1)
  const height=await panel.evaluate(el=>el.getBoundingClientRect().height)
  const handle=panel.getByRole('separator',{name:'调整信息记录高度'})
  await handle.focus(); await handle.press('ArrowUp')
  assert.equal(await panel.evaluate(el=>el.getBoundingClientRect().height),height+16)
  await panel.getByRole('button',{name:'收起信息记录'}).click()
  assert.equal(await panel.locator('.runtime-message-list').isVisible(),false)
  await page.locator('[data-navigation-group="workspace"]').click();await page.getByTestId('workspace').waitFor()
  await panel.getByRole('button',{name:'展开信息记录'}).click()
  assert.equal(await panel.locator('.runtime-message-list').isVisible(),true)
  check('Global panel survives navigation, supports keyboard resizing and collapse, and remains outside the page scroll area')

  const caps=await call(page,'/api/v1/capabilities')
  const entries=caps.capabilities.flatMap(item=>item.navigation_entries)
  const methods=await call(page,'/api/v1/methods')
  await call(page,'/api/v1/methods/current',{method_id:methods.find(item=>item.status==='active').id})
  result.layouts=[]
  for(const [theme,density,width,height] of [['light','comfortable',1440,1000],['dark','compact',1060,680]]) {
    const settings=await call(page,'/api/v1/settings')
    await call(page,'/api/v1/settings',{display:{...settings.display,theme,density}},'PATCH')
    await page.reload();await page.getByTestId('workspace').waitFor()
    await workspaceReady()
    await page.locator(`.app-shell[data-theme="${theme}"][data-density="${density}"]`).waitFor()
    assert.equal(await panel.locator('.runtime-message-list').isVisible(),true)
    if(process.env.QA_CDP) await page.evaluate(({width,height})=>window.__TAURI__.core.invoke('plugin:window|set_size',{value:{Logical:{width,height}}}),{width,height})
    else await page.setViewportSize({width,height})
    await page.waitForFunction(width=>Math.abs(innerWidth-width)<2,width)
    for(const entry of entries) {
      await page.locator('[data-navigation-group="workspace"]').click();await page.getByTestId('workspace').waitFor()
      if(entry.group!=='workspace')await navigate(page,entry.group,entry.label,'.page-scroll-region > .page-content')
      await page.waitForFunction(label=>document.querySelector('.breadcrumbs strong')?.textContent===label,entry.label)
      await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
      const layout=await page.evaluate(()=>{
        const panel=document.querySelector('.runtime-message-panel').getBoundingClientRect()
        const region=document.querySelector('.page-scroll-region').getBoundingClientRect()
        const toolbar=document.querySelector('.runtime-message-toolbar')
        return {bottom:panel.bottom,top:panel.top,contentBottom:region.bottom,width:innerWidth,height:innerHeight,
          overflow:document.documentElement.scrollWidth>innerWidth,toolbarOverflow:toolbar.scrollWidth>toolbar.clientWidth}
      })
      result.layouts.push({theme,density,key:entry.key,...layout})
      assert.ok(Math.abs(layout.bottom-layout.height)<2,`${entry.key}: footer not at bottom`)
      assert.ok(layout.contentBottom<=layout.top+1,`${entry.key}: content covers footer`)
      assert.equal(layout.overflow,false,`${entry.key}: horizontal overflow`)
      assert.equal(layout.toolbarOverflow,false,`${entry.key}: toolbar overflow`)
    }
    await page.locator('[data-navigation-group="workspace"]').click();await page.getByTestId('workspace').waitFor()
    await page.locator('.toast').waitFor({state:'hidden'})
    await page.mouse.move(10,10)
    await page.screenshot({path:path.join(output,`information-${theme}.png`),fullPage:true})
    const before=await page.getByTestId('workspace').locator('.workspace-grid').evaluate(element=>Array.from(element.children).map(column=>({
      x:column.getBoundingClientRect().x,width:column.getBoundingClientRect().width,
      cards:Array.from(column.children).map(card=>({x:card.getBoundingClientRect().x,width:card.getBoundingClientRect().width,top:card.getBoundingClientRect().top,height:card.getBoundingClientRect().height}))
    })))
    await panel.getByRole('button',{name:'收起信息记录'}).click()
    const after=await page.getByTestId('workspace').locator('.workspace-grid').evaluate(element=>Array.from(element.children).map(column=>({
      x:column.getBoundingClientRect().x,width:column.getBoundingClientRect().width,
      cards:Array.from(column.children).map(card=>({x:card.getBoundingClientRect().x,width:card.getBoundingClientRect().width,top:card.getBoundingClientRect().top,height:card.getBoundingClientRect().height}))
    })))
    assert.deepEqual(after,before,'Opening or folding the footer must not rearrange workbench cards')
    await page.reload();await page.getByTestId('workspace').waitFor()
    await workspaceReady()
    await page.locator(`.app-shell[data-theme="${theme}"][data-density="${density}"]`).waitFor()
    assert.equal(await panel.locator('.runtime-message-list').isVisible(),false)
    await page.mouse.move(10,10)
    await page.screenshot({path:path.join(output,`workspace-restored-${theme}.png`),fullPage:true})
    await panel.getByRole('button',{name:'展开信息记录'}).click()
  }
  check('All 25 entries keep the footer visible in large/light and minimum/dark layouts without horizontal overflow')
}
