import assert from 'node:assert/strict'
import path from 'node:path'
import { call, navigate } from './contract_browser_support.mjs'

export async function runManualAudit(page, result, output) {
  const original = (await call(page, '/api/v1/methods')).find(item => item.status === 'active')
  const created = await call(page, '/api/v1/methods', { name: '手动转角方法关联验证', conditions: {
    ...original.version.conditions, selected_ccds: [0, 2, 4], angle_exposures: [
      { angle_deg: 10, storage_mode: 'averaged', start_frame: 1, end_frame: 2 },
      { angle_deg: 20, storage_mode: 'full_interval', start_frame: 1, end_frame: 2 },
      { angle_deg: 30, storage_mode: 'averaged', start_frame: 1, end_frame: 2 }
    ]
  } })
  const method = await call(page, `/api/v1/methods/${created.id}/publish`, {})
  const methodChoice = `${method.id}-${method.current_version}`
  await page.reload(); await page.getByTestId('workspace').waitFor()
  await navigate(page, 'analysis-tests', '自动转角采集', '[data-testid="hardware-acquisition-page"]')
  if (process.env.QA_CDP) await page.evaluate(() => window.__TAURI__.core.invoke('plugin:window|set_size', { value: { Logical: { width:1440,height:1000 } } }))
  else await page.setViewportSize({width:1440,height:1000})
  await page.evaluate(() => { document.documentElement.dataset.theme='light' })
  const host=page.getByTestId('hardware-acquisition-page'), dialog=host.getByRole('dialog')
  await page.getByRole('button',{name:'新建任务',exact:true}).click()
  await dialog.getByRole('button',{name:'手动',exact:true}).click()
  await dialog.getByLabel('采集方法',{exact:true}).selectOption(methodChoice)
  assert.equal(await dialog.getByLabel('采集方法',{exact:true}).isVisible(),true)
  assert.equal(await dialog.getByLabel('转角顺序',{exact:true}).count(),0)
  await dialog.getByLabel('任务名称',{exact:true}).fill('手动角度与时长验证')
  const fill=async(index,angle,duration)=>{
    await dialog.getByLabel(`手动角度 ${index}`,{exact:true}).selectOption(String(angle))
    await dialog.getByLabel(`采集时长 ${index}`,{exact:true}).fill(String(duration))
  }
  await fill(1,20,2.5)
  await dialog.getByRole('button',{name:'新增转角',exact:true}).click();await fill(2,10,1.2)
  await dialog.getByRole('button',{name:'新增转角',exact:true}).click();await fill(3,20,2.2)
  await dialog.getByRole('button',{name:'新增转角',exact:true}).click()
  await dialog.getByRole('button',{name:'删除转角 4',exact:true}).click()
  await dialog.getByRole('button',{name:'上移转角 2',exact:true}).click()
  assert.equal(await dialog.getByLabel('手动角度 1',{exact:true}).inputValue(),'10')
  await dialog.getByRole('button',{name:'下移转角 1',exact:true}).click()
  await dialog.getByRole('button',{name:'自动',exact:true}).click()
  assert.equal(await dialog.getByLabel('手动角度 1',{exact:true}).count(),0)
  assert.equal(await dialog.getByRole('button',{name:'新增转角',exact:true}).count(),0)
  assert.equal(await dialog.locator('.hardware-turn-angles').count(),0)
  assert.equal(await dialog.getByLabel('调试转角计划 JSON',{exact:true}).count(),0)
  assert.equal(await dialog.getByLabel('采集方法',{exact:true}).isVisible(),true)
  await dialog.getByRole('button',{name:'手动',exact:true}).click()
  assert.equal(await dialog.getByLabel('手动角度 1',{exact:true}).inputValue(),'20')
  await dialog.getByRole('button',{name:'取消',exact:true}).click()
  await page.getByRole('button',{name:'新建任务',exact:true}).click()
  assert.equal(await dialog.getByRole('button',{name:'手动',exact:true}).getAttribute('aria-pressed'),'true')
  await dialog.getByLabel('采集时长 1',{exact:true}).fill('0')
  await dialog.getByRole('button',{name:'建立任务',exact:true}).click()
  assert.equal(await dialog.isVisible(),true)
  await dialog.getByLabel('采集时长 1',{exact:true}).fill('2.5')
  assert.equal(await dialog.getByLabel('手动角度 1',{exact:true}).locator('option').count(),4)
  assert.equal(await dialog.getByText('方法计算配置',{exact:true}).isVisible(),true)
  assert.ok((await dialog.locator('tbody tr').first().innerText()).includes('全区间'))
  await page.screenshot({path:path.join(output,'manual-task-form.png')})
  await dialog.getByLabel('采集时长 1',{exact:true}).fill('.3')
  await dialog.getByRole('button',{name:'建立任务',exact:true}).click()
  await dialog.getByRole('alert').filter({hasText:'采集时长不足以覆盖方法计算区间'}).waitFor()
  await page.screenshot({path:path.join(output,'manual-interval-error.png')})
  await dialog.getByLabel('采集时长 1',{exact:true}).fill('2.5')
  await dialog.getByRole('button',{name:'建立任务',exact:true}).click()
  await host.locator('.hardware-capture-desk').waitFor()
  let task=(await call(page,'/api/v1/hardware-acquisitions/tasks'))[0]
  assert.equal(task.execution_mode,'manual'); assert.equal(task.method_id,method.id)
  assert.equal(task.method_version,method.current_version)
  assert.deepEqual(task.steps.map(row=>row.angle_deg),[20,10,20])
  assert.deepEqual(task.steps.map(row=>row.duration_seconds),[2.5,1.2,2.2])
  assert.deepEqual(task.plan.map(row=>row.ccd_indices),[[2],[0],[2]])
  assert.deepEqual(task.plan.map(row=>row.storage_mode),['full_interval','averaged','full_interval'])
  assert.ok(task.steps.every(row=>typeof row.wavelength_nm==='number'))
  assert.equal(await host.getByText('未配置方法监测线',{exact:true}).count(),0)
  assert.equal(await host.getByText('短波 → 长波',{exact:true}).count(),0)
  await host.getByRole('button',{name:'开始采集',exact:true}).click()
  await host.getByTestId('spectrum-plot').waitFor()
  await host.getByRole('button',{name:'暂停采集',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.hardware-monitor .state-chip')?.classList.contains('paused'))
  const paused=await call(page,`/api/v1/hardware-acquisitions/tasks/${task.id}`)
  assert.equal(paused.completed_steps,0);assert.ok(paused.frames.length)
  assert.ok(paused.frames.every(row=>!row.confirmed))
  assert.equal(await host.getByLabel('当前采集时长',{exact:true}).isVisible(),true)
  assert.equal(await host.getByText('未完成采集，数据暂未确认',{exact:true}).isVisible(),true)
  assert.equal(await host.getByRole('heading',{name:'转角顺序与时长',exact:true}).isVisible(),true)
  await page.waitForTimeout(1300)
  const during=await call(page,`/api/v1/hardware-acquisitions/tasks/${task.id}`)
  assert.equal(during.frames.length,paused.frames.length)
  assert.equal(during.steps[0].captured_seconds,paused.steps[0].captured_seconds)
  await page.screenshot({path:path.join(output,'manual-capture-paused.png')})
  await host.getByRole('button',{name:'继续采集',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.hardware-monitor .state-chip')?.classList.contains('completed'))
  task=await call(page,`/api/v1/hardware-acquisitions/tasks/${task.id}`)
  assert.equal(task.completed_steps,3)
  assert.deepEqual(task.traces.filter(row=>row.name==='turn.request').map(row=>row.payload.angle_deg),[20,10,20])
  assert.ok(task.exposures.length && task.exposures.every(row=>row.confirmed))
  assert.ok(task.exposures.some(row=>row.end_frame>1))
  assert.ok(task.result_sha256)
  assert.deepEqual(task.steps.map(row=>row.captured_seconds),[2.5,1.2,2.2])
  assert.equal(await host.getByText('保存分析样品',{exact:true}).count(),1)
  assert.ok(task.exposures.every(row=>row.end_frame===2))
  await page.screenshot({path:path.join(output,'manual-capture-completed.png')})
  await page.getByRole('button',{name:'返回任务列表',exact:true}).click()
  result.checks.push('Manual mode selects published method and only its angles; add/delete/reorder and mode/cancel drafts retained; insufficient method interval rejected')
  result.checks.push('Manual repeated and reordered angles retain their own method CCD/storage/interval; timed collection and pause work, calculation interval stays fixed while extra raw frames remain')
}
