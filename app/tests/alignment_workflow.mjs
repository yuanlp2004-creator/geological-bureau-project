import assert from 'node:assert/strict'
import path from 'node:path'

// Run after a real simulator Stop, so incoming frames cannot change the comparison.
export async function checkAlignmentViews(page, debug, result, output) {
  const views = debug.locator('.alignment-row')
  assert.equal(await views.count(), 3)
  assert.equal(await debug.locator('svg.alignment-plot').count(), 3)
  const picker = debug.getByLabel('设定 CCD', { exact: true })
  assert.equal(await picker.isDisabled(), true)
  const initial = await views.evaluateAll(nodes => nodes.map(node => node.dataset.ccd))
  await debug.getByRole('button', { name: '选择视图区 2', exact: true }).click()
  assert.equal(await picker.isEnabled(), true)
  const unused = await picker.locator('option:not(:disabled)').evaluateAll(nodes => nodes.map(node => node.value))
  const next = unused.find(value => value !== initial[1])
  assert.ok(next, 'seed profile must include an unused CCD')
  await picker.selectOption(next)
  assert.deepEqual(await views.evaluateAll(nodes => nodes.map(node => node.dataset.ccd)), [initial[0], next, initial[2]])
  for (const ccd of [initial[0], initial[2]]) assert.equal(await picker.locator(`option[value="${ccd}"]`).evaluate(option=>option.disabled), true, JSON.stringify(await picker.locator('option').evaluateAll(nodes=>nodes.map(node=>({value:node.value,disabled:node.disabled})))) )
  const second = views.nth(1), svg = second.locator('svg')
  const span = async view => Number(await view.getAttribute('data-x-max')) - Number(await view.getAttribute('data-x-min'))
  const unchangedFirst = await span(views.nth(0)), full = await span(second)
  const peak = await debug.getByLabel('最大峰值', { exact: true }).innerText()
  assert.match(peak, /^最大峰值强度:\d+ 位置:\(\d+, \d+\)$/)
  const bounds = await svg.boundingBox()
  await svg.hover({ position: { x: bounds.width * .37, y: bounds.height * .6 } })
  const raw = await debug.getByLabel('当前点位读数', { exact: true }).innerText()
  assert.match(raw, /强度:\d+.*位置:/)
  await debug.getByLabel('扣除背景', { exact: true }).uncheck()
  assert.equal(Number(await second.getAttribute('data-y-min')), 0)
  await svg.hover({ position: { x: bounds.width * .37, y: bounds.height * .6 } })
  assert.equal(await debug.getByLabel('当前点位读数', { exact: true }).innerText(), raw)
  assert.equal(await debug.getByLabel('最大峰值', { exact: true }).innerText(), peak)
  await debug.getByLabel('扣除背景', { exact: true }).check()
  const min = Number(await second.getAttribute('data-y-min')), max = Number(await second.getAttribute('data-y-max'))
  assert.ok(min > 0)
  await debug.getByRole('button', { name: '横向放大', exact: true }).click()
  assert.ok(await span(second) < full)
  assert.equal(await span(views.nth(0)), unchangedFirst)
  assert.equal(await debug.locator('.alignment-x-range input[type="range"]').count(), 0)
  const pointReadout = async () => Number((await debug.getByLabel('当前点位读数').innerText()).match(/位置:\(\d+, (\d+)\)/)?.[1])
  const firstVisible = Math.ceil(Number(await second.getAttribute('data-x-min')))
  await svg.press('ArrowLeft')
  assert.equal(await pointReadout(), firstVisible - 1)
  assert.equal(Number(await second.getAttribute('data-x-min')), firstVisible - 1)
  const lastVisible = Math.floor(Number(await second.getAttribute('data-x-max')))
  const zoomedBox = await svg.boundingBox()
  await svg.hover({ position: { x: zoomedBox.width - 2, y: zoomedBox.height / 2 } })
  let target = await pointReadout()
  assert.ok(Number.isFinite(target))
  do {
    await svg.press('ArrowRight')
    target += 1
  } while (target <= lastVisible)
  assert.equal(await pointReadout(), target)
  assert.ok(Math.abs(Number(await second.getAttribute('data-x-max')) - target) < 1e-6)
  assert.equal(await span(views.nth(0)), unchangedFirst)
  await debug.getByRole('button', { name: '纵向放大', exact: true }).click()
  assert.equal(Number(await second.getAttribute('data-zoom-y')), 2)
  assert.ok(Math.abs(Number(await second.getAttribute('data-y-max')) - (min + (max - min) / 2)) < .001)
  await debug.getByRole('button', { name: '适合图像', exact: true }).click()
  assert.equal(await span(second), full)
  assert.equal(Number(await second.getAttribute('data-zoom-y')), 2, 'legacy Fit only resets X')
  await debug.getByRole('button', { name: '一线一点', exact: true }).click()
  const one = await span(second)
  await debug.getByRole('button', { name: '一线四点', exact: true }).click()
  assert.ok(await span(second) < one)
  await debug.getByRole('button', { name: '还原全部 CCD 视图', exact: true }).click()
  assert.equal(await span(second), full)
  assert.deepEqual(await views.evaluateAll(nodes => nodes.map(node => Number(node.dataset.zoomY))), [1, 1, 1])
  await debug.getByRole('button', { name: '区域放大', exact: true }).click()
  const box = await svg.boundingBox()
  await page.mouse.move(box.x + box.width * .3, box.y + box.height * .3)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .7, box.y + box.height * .6, { steps: 5 })
  await page.mouse.up()
  assert.ok(await span(second) < full)
  await debug.getByRole('button', { name: '还原全部 CCD 视图', exact: true }).click()
  await debug.screenshot({ path: path.join(output, 'alignment-three-ccds.png') })
  result.checks.push('Legacy alignment: three live CCDs, fixed first CCD, distinct secondary selections, raw readouts, background floor, independent zoom, keyboard panning without a slider, pixel scales, box zoom and reset')
}
