import assert from 'node:assert/strict'
import path from 'node:path'
import { call, navigate } from './contract_browser_support.mjs'
import { leaveLegacyCapture, waitForSpectrumInk } from './legacy_desk_test_support.mjs'

export async function checkSampleTurnIntegration(page, result, output) {
  const check = message => result.checks.push(message)
  const caps = await call(page, '/api/v1/capabilities')
  assert.ok(!caps.capabilities.flatMap(module => module.navigation_entries ?? []).some(entry => entry.page === 'hardware-acquisition'))
  check('独立自动转角入口从正式导航清单移除，历史接口仍可读取')
  assert.ok(Array.isArray(await call(page, '/api/v1/hardware-acquisitions/tasks')))
  assert.ok(Array.isArray(await call(page, '/api/v1/mercury-calibrations/sessions')))
  const reviewQueue = await call(page, '/api/v1/sample-queues', { name: `转角核对-${Date.now().toString(36)}`,
    name_length: 20, items: [{ pre_name: 'TURN001', repeats: 2 }, { pre_name: 'TURN002', repeats: 1 }] })
  await call(page, '/api/v1/sample-queues/current', { queue_id: reviewQueue.id }, 'PUT')
  await navigate(page, 'analysis-tests', '样品摄谱', '[data-testid="sample-acquisition-page"]')
  const host = page.getByTestId('sample-acquisition-page')
  await leaveLegacyCapture(page)
  await page.getByRole('button', { name: '新建任务', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '样品摄谱', exact: true })
  await dialog.waitFor()
  assert.equal(await dialog.locator('input').count(), 1)
  assert.equal(await dialog.locator('select').count(), 0)
  const name = `转角完整重复-${Date.now().toString(36)}`
  await dialog.getByRole('textbox').fill(name)
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  const console = host.getByTestId('spectroscopy-console')
  await console.waitFor()
  const waitForSampleStatus = status => page.waitForFunction(expected => document.querySelector('[data-testid="sample-acquisition-page"] .acquisition-monitor')?.getAttribute('data-status') === expected, status, { timeout: 45000 })
  const created = (await call(page, '/api/v1/acquisitions/tasks')).find(task => task.name === name)
  assert.ok(created)
  const current = () => call(page, `/api/v1/acquisitions/tasks/${created.id}`)
  assert.deepEqual(created.turns.plan.map(turn => turn.angle_deg), [17, 4])
  const pages = console.getByRole('navigation', { name: '转角摄谱页面' })
  const firstAngle = pages.getByRole('button', { name: /^17°/ })
  const secondAngle = pages.getByRole('button', { name: /^4°/ })
  await secondAngle.click()
  assert.equal(await secondAngle.getAttribute('aria-pressed'), 'true')
  assert.equal(await console.getByRole('button', { name: '仅摄本转角', exact: true }).isDisabled(), true)
  check('样品新建仅填写编号；全部转角、关键波段和顺序取确切发布方法')
  await console.getByRole('button', { name: '预热摄谱', exact: true }).click()
  await waitForSampleStatus('completed')
  assert.equal(await secondAngle.getAttribute('aria-pressed'), 'true')
  assert.equal((await current()).completed_repeats, 0)
  await console.getByRole('button', { name: '返回正式任务', exact: true }).click()
  check('预热只在所选转角执行，不占用正式样号及重复次数')
  const start = console.getByRole('button', { name: '试样摄谱', exact: true })
  const startOne = console.getByRole('button', { name: '仅摄本转角', exact: true })
  await startOne.click()
  await waitForSampleStatus('paused')
  let task = await current()
  assert.equal(task.turns.awaiting_turn, true)
  assert.equal(task.completed_repeats, 0)
  assert.deepEqual(task.samples[0].bands, [])
  await page.waitForFunction(() => document.querySelector('[data-testid="sample-acquisition-page"] .capture-turn-pages [aria-pressed=true]')?.textContent.startsWith('4°'))
  await firstAngle.click()
  await waitForSpectrumInk(console)
  assert.equal(await startOne.isDisabled(), true)
  await secondAngle.click()
  await startOne.click()
  await waitForSampleStatus('between_repeats')
  task = await current()
  assert.equal(task.completed_repeats, 1)
  assert.equal(task.samples.length, 1)
  assert.deepEqual(task.samples[0].bands.map(band => [band.angle_deg, band.ccd_index]), [[17, 0], [4, 0]])
  assert.deepEqual(task.messages.filter(message => message.code === 'sample.turn.positioned').map(message => message.details.angle_deg), [17, 4])
  assert.equal(task.progress, 50)
  await page.waitForTimeout(1300)
  assert.equal((await current()).completed_repeats, 1)
  check('逐角摄谱可查看本轮已采帧；全部转角完成后才计一次重复')
  await start.click()
  await waitForSampleStatus('completed')
  task = await current()
  assert.equal(task.completed_repeats, 2)
  assert.equal(task.samples.length, 2)
  assert.equal(task.progress, 100)
  const queue = await call(page, `/api/v1/sample-queues/${task.queue_id}`)
  assert.equal(queue.items.find(item => item.id === task.queue_item_id).spectrum_hash, task.result_sha256)
  if (await secondAngle.getAttribute('aria-pressed') !== 'true') await secondAngle.click()
  await waitForSpectrumInk(console)
  const beforeBands = await call(page, `/api/v1/acquisitions/samples/${task.samples[0].id}/bands?include_points=true`)
  assert.deepEqual(beforeBands.map(band => band.angle_deg), [17, 4])
  for (const [width, height] of [[1440, 1000], [1060, 760]]) {
    if (page.url().includes('tauri')) await page.evaluate(async size => {
      const { invoke } = window.__TAURI__.core
      await invoke('plugin:window|set_size', { value: { Logical: size } })
    }, { width, height })
    else await page.setViewportSize({ width, height })
    await page.waitForTimeout(250)
    const layout = await console.evaluate(element => ({ width: element.getBoundingClientRect().width,
      overflow: document.documentElement.scrollWidth > innerWidth + 1, pickers: element.querySelectorAll('.legacy-window-caption .capture-turn-pages button').length }))
    assert.equal(layout.overflow, false)
    assert.equal(layout.pickers, 2)
    assert.ok(layout.width > 650)
    await page.screenshot({ path: path.join(output, `sample-turns-${width}.png`) })
    result.layouts ??= []; result.layouts.push({ width, height, ...layout })
  }
  check('两次重复完整保存并回写原队列；查看转角仅观察，宽窄窗口可操作')
  const record = await call(page, `/api/v1/spectra/sample:${task.samples[0].id}?ccd=1&detail=frame&phase=burn&frame=0`)
  assert.equal(record.angle_deg, 4)
  assert.equal(record.ccd.index, 0)
  assert.deepEqual(record.layout.band_labels, ['17° · CCD 1', '4° · CCD 1'])
  const run = await call(page, '/api/v1/analyses/runs', { name: '转角输入核对', acquisition_sample_ids: task.samples.map(sample => sample.id) })
  const spectrum = await call(page, `/api/v1/analyses/runs/${run.id}/spectra/0`)
  assert.deepEqual(spectrum.bands.map(band => [band.angle_deg, band.ccd_index]), [[17, 0], [4, 0]])
  check('谱图查看与分析快照保持转角、CCD、波长及原始帧的同一关联')
  await leaveLegacyCapture(page)
  const failed = await call(page, '/api/v1/acquisitions/tasks', { name: '转角故障核对', method_id: created.method_id,
    method_version: created.method_version, sample_name: '故障样品', repeat_count: 1, fault_frame: 1 })
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await host.locator(`tr[data-task-id="${failed.id}"]`).getByRole('button', { name: '进入摄谱', exact: true }).click()
  await start.click()
  await waitForSampleStatus('failed')
  const failedTask = await call(page, `/api/v1/acquisitions/tasks/${failed.id}`)
  assert.equal(failedTask.completed_repeats, 0)
  assert.equal(failedTask.samples[0].finalized, false)
  assert.equal(failedTask.samples[0].bands.length, 0)
  check('采集故障保留已收帧并安全结束，不确认不完整重复')
  await leaveLegacyCapture(page)
  await host.locator(`tr[data-task-id="${created.id}"]`).getByRole('button', { name: '查看谱图', exact: true }).click()
  const viewer = page.getByTestId('spectrum-viewer-page')
  await waitForSpectrumInk(viewer)
  assert.equal(await viewer.getAttribute('data-file-group'), `task:${created.id}`)
  assert.deepEqual((await call(page, `/api/v1/acquisitions/samples/${task.samples[0].id}/bands?include_points=true`)), beforeBands)
  result.sampleTaskId = task.id
  result.methodId = task.method_id
}

export async function checkPreliminaryTurnPages(page, result, output) {
  for (const [kind, label, testId, dialogName, base] of [
    ['dispersion', '色散摄谱', 'dispersion-page', '色散曲线摄谱', '/api/v1/dispersion/tasks'],
    ['evaporation', '蒸发摄谱', 'evaporation-acquisition-page', '蒸发曲线摄谱', '/api/v1/acquisitions/tasks']
  ]) {
    await leaveLegacyCapture(page)
    await navigate(page, 'analysis-tests', label, `[data-testid="${testId}"]`)
    await page.getByRole('button', { name: '新建任务', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: dialogName, exact: true })
    const name = `角度核对-${kind}-${Date.now().toString(36)}`
    await dialog.getByLabel(kind === 'dispersion' ? '色散曲线名' : '蒸发曲线名').fill(name)
    for (const [field, value] of [['预激时间（秒）', '1'], ['采样周期（秒）', '1'], ['采样次数', '2'], ['空白次数', '0']])
      await dialog.getByLabel(field, { exact: true }).fill(value)
    await dialog.getByRole('button', { name: '确定', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    const desk = page.getByTestId(testId).getByTestId('spectroscopy-console')
    const tabs = desk.getByRole('navigation', { name: '转角摄谱页面' })
    const first = tabs.getByRole('button', { name: /^17°/ }), second = tabs.getByRole('button', { name: /^4°/ })
    const waitForAngle = angle => page.waitForFunction(({ testId, angle }) =>
      document.querySelector(`[data-testid="${testId}"] .capture-turn-pages [aria-pressed=true]`)?.textContent.startsWith(`${angle}°`), { testId, angle })
    await second.click()
    await waitForAngle(4)
    const created = (await call(page, base)).filter(task => task.name === name)
    const byAngle = angle => created.find(task => task.capture_turn?.angle_deg === angle)
    assert.equal(created.length, 2)
    assert.ok(byAngle(4) && byAngle(17))
    await desk.getByRole('button', { name: '试样摄谱', exact: true }).click()
    await page.waitForFunction(id => document.querySelector(`[data-testid="${id}"] .legacy-capture-desk`)?.getAttribute('data-status') === 'completed', testId)
    assert.equal((await call(page, `${base}/${byAngle(17).id}`)).status, 'draft')
    assert.equal((await call(page, `${base}/${byAngle(4).id}`)).status, 'completed')
    await first.click()
    await waitForAngle(17)
    assert.equal(await desk.getByRole('button', { name: '试样摄谱', exact: true }).isEnabled(), true)
    await second.click()
    await waitForAngle(4)
    assert.equal(await desk.getByRole('button', { name: '试样摄谱', exact: true }).isDisabled(), true)
    await page.screenshot({ path: path.join(output, `${kind}-turns.png`) })
    result.checks.push(`${label}标题行切换到4°并完成摄谱，17°仍待采；切回已采角度显示自己的谱图与控制状态`)
  }
}
